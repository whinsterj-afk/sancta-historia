begin;

create table public.map_landmarks (
  id bigint generated by default as identity primary key,
  place_id bigint not null references public.places(id) on delete cascade,
  kind text not null,
  title text not null,
  description text,
  start_year integer,
  end_year integer,
  source_url text,
  is_published boolean not null default true,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  constraint map_landmarks_kind_values
    check (kind in ('important_city', 'episcopal_see', 'pilgrimage_site')),
  constraint map_landmarks_title_nonempty
    check (trim(title) <> ''),
  constraint map_landmarks_period_valid
    check (end_year is null or start_year is null or end_year >= start_year),
  constraint map_landmarks_place_kind_key
    unique (place_id, kind)
);

create index map_landmarks_timeline_idx
  on public.map_landmarks(start_year, end_year)
  where is_published;

create trigger map_landmarks_set_updated_at
before update on public.map_landmarks
for each row execute function public.set_updated_at();

alter table public.map_landmarks enable row level security;

create policy "Public landmarks are readable"
on public.map_landmarks
for select
to anon, authenticated
using (is_published);

grant select on public.map_landmarks to anon, authenticated;

