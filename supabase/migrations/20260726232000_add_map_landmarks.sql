create view public.timeline_map_landmarks
with (security_invoker = true)
as
select
  landmarks.id,
  landmarks.kind,
  landmarks.title,
  landmarks.description,
  landmarks.start_year,
  landmarks.end_year,
  places.name as location_name,
  places.latitude,
  places.longitude
from public.map_landmarks as landmarks
join public.places on places.id = landmarks.place_id
where landmarks.is_published
  and places.is_published
  and places.latitude is not null
  and places.longitude is not null;

